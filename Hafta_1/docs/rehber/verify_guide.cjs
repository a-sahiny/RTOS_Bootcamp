const { chromium } = require('C:/Users/Asus/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const path=require('path');
const fs=require('fs');
const {pathToFileURL}=require('url');
(async()=>{
  const root=path.resolve(__dirname,'../..');
  const qa=path.join(root,'tmp/pdfs/qa');fs.mkdirSync(qa,{recursive:true});
  const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1080},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(root,'output/rehber/rtos_kod_rehberi.html')).href);
  await page.screenshot({path:path.join(qa,'html-desktop.png')});
  const initial=await page.evaluate(()=>({chapters:document.querySelectorAll('.chapter').length,nav:document.querySelectorAll('.nav a').length,sourceBlocks:document.querySelectorAll('.source').length,documentOverflow:document.documentElement.scrollWidth>innerWidth,missingTargets:[...document.querySelectorAll('a[href^="#"]')].filter(a=>!document.getElementById(a.hash.slice(1))).map(a=>a.hash)}));
  await page.locator('#search').fill('semaphore');
  const searchCount=await page.locator('.chapter:visible').count();
  if(searchCount===0 || searchCount===22)throw Error('Search did not filter');
  await page.locator('#search').fill('bu_kelime_yok_12345');
  if(!await page.locator('.no-results').isVisible())throw Error('Empty result message missing');
  await page.locator('#search').fill('');
  await page.locator('.steps button').nth(5).click();
  if(!await page.locator('#step-title').textContent().then(t=>t.includes('Bitişi')))throw Error('Stepper failed');
  await page.locator('#theme').click();
  if(!await page.locator('body').evaluate(e=>e.classList.contains('dark')))throw Error('Theme failed');
  await page.locator('#ch11').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(qa,'html-code-dark.png')});
  await page.locator('#theme').click();
  await page.locator('#ch15').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(qa,'html-ring.png')});
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>{document.documentElement.style.scrollBehavior='auto';window.scrollTo(0,0)});
  await page.waitForFunction(()=>scrollY===0 && document.querySelector('.sidebar').getBoundingClientRect().right<=0);
  await page.screenshot({path:path.join(qa,'html-mobile.png'),animations:'disabled'});
  const mobile=await page.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth,width:document.documentElement.scrollWidth}));
  await page.locator('.mobile-menu').click();
  if(await page.locator('.mobile-menu').getAttribute('aria-expanded')!=='true')throw Error('Mobile menu failed');
  await page.locator('.nav a[href="#ch14"]').click();
  if(await page.locator('.mobile-menu').getAttribute('aria-expanded')!=='false')throw Error('Mobile menu did not close');
  await browser.close();
  if(errors.length || initial.documentOverflow || mobile.overflow || initial.missingTargets.length)throw Error(JSON.stringify({errors,initial,mobile}));
  const result={initial,searchCount,mobile,errors,checks:['search','empty results','seven-step walkthrough','theme','mobile menu','internal links','responsive overflow']};
  fs.writeFileSync(path.join(qa,'html-checks.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
})().catch(e=>{console.error(e);process.exit(1)});
